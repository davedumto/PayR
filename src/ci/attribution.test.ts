import { describe, expect, it } from "vitest";

import { findAttributionViolations, type CommitMessage } from "@/ci/attribution";

function commit(message: string): CommitMessage {
  return { sha: "abc1234", message };
}

describe("findAttributionViolations", () => {
  const cases: readonly { name: string; message: string; expected: number }[] = [
    { name: "plain subject and body", message: "feat: add thing\n\nBody text.", expected: 0 },
    {
      name: "Co-Authored-By naming Claude",
      message: "feat: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>",
      expected: 1,
    },
    {
      name: "Co-Authored-By naming Claude, lowercase",
      message: "feat: x\n\nco-authored-by: claude <noreply@example.com>",
      expected: 1,
    },
    {
      name: "Co-Authored-By naming Anthropic",
      message: "feat: x\n\nCo-Authored-By: Someone <someone@anthropic.com>",
      expected: 1,
    },
    {
      name: "Co-Authored-By with leading whitespace",
      message: "feat: x\n\n   Co-Authored-By: Claude <noreply@anthropic.com>",
      expected: 1,
    },
    {
      name: "Claude-Session trailer",
      message: "feat: x\n\nClaude-Session: https://claude.ai/code/session_abc",
      expected: 1,
    },
    {
      name: "Generated with Claude Code footer",
      message: "feat: x\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)",
      expected: 1,
    },
    {
      name: "Generated by Claude Code footer",
      message: "feat: x\n\n_Generated by [Claude Code](https://claude.ai/code/session_abc)_",
      expected: 1,
    },
    {
      name: "human co-author is allowed",
      message: "feat: x\n\nCo-Authored-By: Dana Lee <dana@example.com>",
      expected: 0,
    },
    {
      name: "product text mentioning Claude is not attribution",
      message: "docs: say there is no Claude call yet\n\nThe proxy has no Claude calls.",
      expected: 0,
    },
    {
      name: "ANTHROPIC_API_KEY config text is not attribution",
      message: "chore: add ANTHROPIC_API_KEY to env template",
      expected: 0,
    },
    {
      name: "trailer text in the middle of a sentence is not a trailer",
      message: "docs: explain why we drop Co-Authored-By: Claude lines",
      expected: 0,
    },
    {
      name: "both trailers in one commit report two violations",
      message:
        "feat: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>\nClaude-Session: https://claude.ai/code/x",
      expected: 2,
    },
  ];

  for (const testCase of cases) {
    it(testCase.name, () => {
      expect(findAttributionViolations([commit(testCase.message)])).toHaveLength(testCase.expected);
    });
  }

  it("reports the commit sha, the offending line and the reason", () => {
    const [violation] = findAttributionViolations([
      { sha: "deadbeef", message: "feat: x\n\nClaude-Session: https://claude.ai/code/x" },
    ]);
    expect(violation).toEqual({
      sha: "deadbeef",
      line: "Claude-Session: https://claude.ai/code/x",
      reason: "Claude-Session trailer",
    });
  });

  it("checks every commit in the list", () => {
    const violations = findAttributionViolations([
      { sha: "good", message: "feat: fine" },
      { sha: "bad", message: "feat: x\n\nClaude-Session: https://claude.ai/code/x" },
    ]);
    expect(violations.map((v) => v.sha)).toEqual(["bad"]);
  });

  it("returns no violations for an empty range", () => {
    expect(findAttributionViolations([])).toEqual([]);
  });
});
